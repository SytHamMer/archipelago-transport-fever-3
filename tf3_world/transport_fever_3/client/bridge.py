"""The file exchange with the TF3 mod: the client writes the inbox and reads the outbox of its seed."""
import os
import re
import time
from dataclasses import dataclass
from pathlib import Path

from .. import data
from . import luafile

INBOX_NAME = "archipelago_tf3_inbox.lua"
OUTBOX_PREFIX = "archipelago_tf3_outbox_"  # one outbox per seed, so seeds never share progress
FORMAT_VERSION = 1
REPLACE_ATTEMPTS = 5  # the game or a scanner may hold the inbox open for a moment on Windows
REPLACE_DELAY = 0.05


@dataclass(frozen=True)
class Outbox:
    seed: str
    checks: set
    goals: dict
    applied: int
    heartbeat: int
    year: int | None = None  # in-game year, absent in outboxes written by older mod versions


def _effect(index: int, name: str) -> dict | None:
    """One-shot effect for a received item (None for items that are state, not effects)."""
    if name in data.MONEY_ITEMS:
        return {"id": index, "kind": "money", "amount": data.MONEY_ITEMS[name]}
    if name in data.TRAPS:
        return {"id": index, "kind": "money_loss", "amount": data.TRAPS[name]}
    return None


def safe_seed(seed: str) -> str:
    """The seed as it appears in the outbox file name (the mod applies the same rule)."""
    return re.sub(r"[^A-Za-z0-9_-]", "_", seed)


class Bridge:
    def __init__(self, userdata_dir: Path, seed: str | None = None):
        self.dir = Path(userdata_dir)
        self.seed = seed

    def outbox_path(self) -> Path:
        return self.dir / f"{OUTBOX_PREFIX}{safe_seed(self.seed or '')}.lua"

    def write_inbox(self, slot_data: dict, received: list[str], log: list[dict] | None = None) -> None:
        """Write the complete wanted state. `received` is the full ordered list of items received so far.

        `log` (optional) says who sent each of them and for which check, for the in-game notifications.
        """
        self.seed = slot_data["seed"]
        items: dict[str, int] = {}
        effects = []
        for index, name in enumerate(received, start=1):
            items[name] = items.get(name, 0) + 1
            effect = _effect(index, name)
            if effect:
                effects.append(effect)
        config = {"goals": slot_data["goals"], "checks": slot_data["checks"]}
        if "eras" in slot_data:  # seeds generated by an older world version may not carry the era bounds
            config["eras"] = slot_data["eras"]
        inbox = {
            "version": FORMAT_VERSION,
            "seed": slot_data["seed"],
            "config": config,
            "items": items,
            "effects": effects,
        }
        if log is not None:
            inbox["log"] = log
        target = self.dir / INBOX_NAME
        temporary = self.dir / (INBOX_NAME + ".tmp")
        temporary.write_text(luafile.dumps(inbox), encoding="utf-8")
        for attempt in range(REPLACE_ATTEMPTS):
            try:
                os.replace(temporary, target)
                return
            except PermissionError:
                if attempt == REPLACE_ATTEMPTS - 1:
                    temporary.unlink(missing_ok=True)
                    raise
                time.sleep(REPLACE_DELAY)

    def read_outbox(self) -> Outbox | None:
        """The seed's outbox, or None when it is missing, unreadable (for example half written) or incomplete."""
        if self.seed is None:
            return None
        try:
            raw = luafile.loads(self.outbox_path().read_text(encoding="utf-8"))
            if str(raw["seed"]) != self.seed:
                return None
            goals = raw["goals"] or {}
            return Outbox(
                seed=str(raw["seed"]),
                checks=set(raw["checks"]),
                goals=dict(goals),
                applied=int(raw["applied"]),
                heartbeat=int(raw["heartbeat"]),
                year=int(raw["year"]) if "year" in raw else None,
            )
        except (OSError, luafile.LuaFormatError, KeyError, TypeError, ValueError):
            return None

    def new_checks(self, sent: set) -> set:
        outbox = self.read_outbox()
        if outbox is None:
            return set()
        return set(outbox.checks) - set(sent)
