"""Generate tf3_world/transport_fever_3/cargo_data.py from the game's files (read-only).

Usage: python scripts/gen_cargo_data.py "<TF3 install>/base/content"

For each climate and each cargo the world delivers, it records how many industries the cargo depends on (the game's
own `cargoRequiredIndustries`, a measure of how hard the cargo is) and the company rank at which all of them exist
(the game's `companyRankRequiredIndustries`). A cargo that cannot be produced in a climate is left out of it.
"""
import sys
from pathlib import Path

import extract_economy

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "tf3_world" / "transport_fever_3" / "cargo_data.py"
# Cargos the game never asks towns for but that are moved between industries: deliverable when produced and consumed.
INTERMEDIATE = ("grain", "iron_ore", "sand", "wool")
ORDER = ("temperate", "dry", "subarctic", "tropical")


def build(content: Path, cargos: list[str]) -> dict[str, dict[str, tuple[int, int]]]:
    economy = extract_economy.extract(content)
    io = economy["industry_io"]
    table: dict[str, dict[str, tuple[int, int]]] = {}
    for climate in ORDER:
        info = economy["climates"][climate]
        rank_of = {industry: int(rank) for rank, names in info["rank_unlocks"].items() for industry in names}
        table[climate] = {}
        for cargo in cargos:
            needed = info["depends_on"].get(cargo)
            if needed is not None:
                table[climate][cargo] = (len(needed), max([rank_of.get(name, 1) for name in needed] + [1]))
                continue
            producers = [name for name in info["industries"] if cargo in io[name]["out"]]
            consumers = [name for name in info["industries"] if cargo in io[name]["in"]]
            if cargo in INTERMEDIATE and producers and consumers:
                table[climate][cargo] = (1, min(rank_of.get(name, 1) for name in producers))
    return table


def render(table: dict[str, dict[str, tuple[int, int]]]) -> str:
    lines = [
        '"""Which cargos each climate can produce, how many industries each depends on and the company rank it needs.',
        "",
        "Generated by scripts/gen_cargo_data.py from the game's own economy files: do not edit by hand.",
        "`CARGO_BY_CLIMATE[climate][cargo] = (industries the cargo depends on, company rank at which they all exist)`.",
        'A cargo missing from a climate cannot be produced there.',
        '"""',
        "",
        "CARGO_BY_CLIMATE: dict[str, dict[str, tuple[int, int]]] = {",
    ]
    for climate in ORDER:
        lines.append(f'    "{climate}": {{')
        for cargo, (count, rank) in sorted(table[climate].items()):
            lines.append(f'        "{cargo}": ({count}, {rank}),')
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT / "tf3_world" / "transport_fever_3"))
    import importlib.util
    spec = importlib.util.spec_from_file_location("data", ROOT / "tf3_world" / "transport_fever_3" / "data.py")
    data = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(data)
    TARGET.write_text(render(build(Path(sys.argv[1]), list(data.CARGOS))), encoding="utf-8")
    print(f"written {TARGET}")
